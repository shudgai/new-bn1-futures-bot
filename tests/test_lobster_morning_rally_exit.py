def test_lobster_holds_at_0750_and_rides_to_peak_at_0759():
    df = pd.DataFrame(
        LOBSTER_RALLY_DATA,
        columns=['timestamp', 'open', 'high', 'low', 'close', 'volume']
    )
    
    pos = {
        'symbol': '龙虾/USDT',
        'side': 'LONG',
        'entry_price': 0.01844,
        'qty': 50000.0,
        'leverage': 5.0,
        'highest_price': 0.01844,
        'peak_roe': 0.0,
    }

    # 1. 07:50 審查 (第 19 根，索引 19)：不得提前平多！
    sub_0750 = df.iloc[:20].copy()
    quote_0750 = sub_0750.iloc[-1]['close'] # 0.01875
    pos['highest_price'] = sub_0750['high'].max()
    pos['peak_roe'] = (pos['highest_price'] - pos['entry_price']) / pos['entry_price'] * 5.0

    snap_0750 = DataPipeline.calculate_snapshot('龙虾/USDT', sub_0750, current_price=quote_0750, position=pos)
    should_exit_0750, reason_0750, _ = ExitGate.evaluate(pos, snap_0750)

    assert should_exit_0750 is False, f"07:50 剛處於主升浪加速期，不得提前平多！reason: {reason_0750}"
    assert reason_0750 in ("HOLD_LOCKED", "VETO_HOLD")

    # 2. 07:51 ~ 07:59 全程續抱
    for i in range(20, 29):
        sub_i = df.iloc[:i+1].copy()
        q_i = sub_i.iloc[-1]['close']
        pos['highest_price'] = max(pos['highest_price'], sub_i['high'].max())
        pos['peak_roe'] = (pos['highest_price'] - pos['entry_price']) / pos['entry_price'] * 5.0
        snap_i = DataPipeline.calculate_snapshot('龙虾/USDT', sub_i, current_price=q_i, position=pos)
        should_exit_i, reason_i, _ = ExitGate.evaluate(pos, snap_i)
        assert should_exit_i is False, f"第 {i} 根 ({q_i}) 應續抱主升浪到底，不得提前平多！reason: {reason_i}"

    # 3. 08:00 頂部大瀑布砸盤 (第 29 根)，放行出場避險獲利了結！
    sub_0800 = df.iloc[:30].copy()
    quote_0800 = sub_0800.iloc[-1]['close'] # 0.01865
    snap_0800 = DataPipeline.calculate_snapshot('龙虾/USDT', sub_0800, current_price=quote_0800, position=pos)
    should_exit_0800, reason_0800, _ = ExitGate.evaluate(pos, snap_0800)

    assert should_exit_0800 is True, "08:00 天量巨型瀑布砸盤貫穿均線，必須及時獲利避險出場！"
    assert reason_0800 in ("EXIT_BY_EXTREME_WATERFALL", "EARLY_PIVOT_PEAK_EXIT", "EXIT_LONG_AT_PEAK")
